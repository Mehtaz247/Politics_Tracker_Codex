import { buildChartsPageModel } from './charts-shared.js';

const icon = {
  bot: '🤖',
  chart: '📊',
  refresh: '🔄',
};

let trackerData;
let defaultCharts = [];
let generatedCharts = [];
let isGenerating = false;
let generationError = '';
let chartRequestText = '';
let hasAutoGeneratedFromUrl = false;
let hasGeneratedPromptCharts = false;

async function boot() {
  const response = await fetch('/data/daniel-lurie-tracker.json');
  if (!response.ok) throw new Error(`Unable to load tracker data: ${response.status}`);
  trackerData = await response.json();
  chartRequestText = readPromptFromUrl();
  defaultCharts = buildChartsPageModel(trackerData);
  generatedCharts = defaultCharts;
  render();
  if (chartRequestText && !hasAutoGeneratedFromUrl) {
    hasAutoGeneratedFromUrl = true;
    await generateCharts();
  }
}

function render() {
  const data = trackerData;
  const isPromptMode = Boolean(chartRequestText && hasAutoGeneratedFromUrl);
  const isCleanPromptView = isPromptMode && readViewModeFromUrl() === 'clean';
  const chartsToRender = (isPromptMode && !hasGeneratedPromptCharts) ? [] : generatedCharts;
  const chartCount = chartsToRender.length;
  const summarySection = `
    <section class="dashboard-grid summary-grid">
      <article class="metric-card"><div class="metric-icon">📈</div><span>Charts live</span><strong>${chartCount}</strong><p>Default views come from tracker data; new charts appear only when requested</p></article>
      <article class="metric-card"><div class="metric-icon">🗄️</div><span>Observed metrics</span><strong>${data.metrics.filter((metric) => metric.observations?.length).length}</strong><p>Available for AI interpretation and chart selection</p></article>
      <article class="metric-card"><div class="metric-icon">🤖</div><span>AI role</span><strong>Specs only</strong><p>AI interprets data and returns fixed-format chart specs, not frontend code</p></article>
    </section>
  `;
  const chartsSection = `
    <section class="section ${isPromptMode ? 'section-priority' : ''}">
      <div class="panel">
        <div class="section-title">
          <div class="section-icon">${icon.chart}</div>
          <div>
            <p>${isPromptMode ? 'Generated from prompt' : 'Charts'}</p>
            <h2>${isPromptMode ? 'Prompt-driven visualization' : 'On-demand visualizations'}</h2>
          </div>
        </div>
        ${isPromptMode ? `<p class="method-note"><strong>Prompt:</strong> ${escapeHtml(chartRequestText)}</p>` : ''}
        <div class="real-chart-grid">
          ${isGenerating && isPromptMode ? '<div class="empty-state">Generating chart view from the prompt and stored tracker data...</div>' : ''}
          ${!isGenerating && chartsToRender.length ? chartsToRender.map(renderGeneratedChart).join('') : ''}
          ${!isGenerating && !chartsToRender.length ? '<div class="empty-state">No chartable tracker data is available yet. Click Generate charts to ask the backend for chart specs from the latest data.</div>' : ''}
        </div>
      </div>
    </section>
  `;

  const root = document.getElementById('root');
  root.className = isCleanPromptView ? 'clean-prompt-view' : '';
  root.innerHTML = `
    <header class="hero ${isCleanPromptView ? 'hero-compact' : ''}">
      <nav>
        <a class="brand" href="/">${icon.bot} Politics Tracker MVP</a>
        <div class="nav-links">
          <a href="/charts.html">Charts</a>
          <a href="/rss.html">RSS</a>
          <a href="/ai-scrape.html">AI Scrape</a>
        </div>
      </nav>
      <div class="hero-content">
        <div>
          <p class="eyebrow">Visual reporting</p>
          <h1>${isPromptMode ? 'Prompt-generated chart view.' : 'Clean chart views built from the tracker data.'}</h1>
          <p class="hero-copy">${isPromptMode ? 'This view was generated directly from the prompt in the URL. The backend interpreted tracker data and the page rendered the resulting chart spec.' : 'Ask for charts only when you want them. The backend requests fixed chart-spec JSON, then the page renders those specs with existing code.'}</p>
          <div class="chart-action-block">
            <label class="chart-request-box">
              <span>Describe the chart you want</span>
              <textarea class="chart-request-input" placeholder="Example: Show a line chart for homelessness trend and a bar chart comparing public safety indicators.">${escapeHtml(chartRequestText)}</textarea>
            </label>
            <button type="button" class="chart-generate-button" ${isGenerating ? 'disabled' : ''}>${isGenerating ? 'Generating…' : 'Generate charts'}</button>
            <p class="chart-action-warning">this number of charts may be limited in the future;</p>
            ${generationError ? `<p class="chart-action-error">${escapeHtml(generationError)}</p>` : ''}
          </div>
          <div class="hero-tags">
            <span>${icon.refresh} Updated ${new Date(data.subject.lastUpdated).toLocaleDateString()}</span>
            <span>${chartCount} chart types visible</span>
            <span>${data.metrics.filter((metric) => metric.observations?.length).length} metrics with observations</span>
          </div>
        </div>
        <div class="hero-card">
          <div class="metric-icon">${icon.chart}</div>
          <strong>${chartCount}</strong>
          <p>Default charts come from saved tracker data, and AI requests return structured specs instead of UI code.</p>
        </div>
      </div>
    </header>
    ${isCleanPromptView ? chartsSection : (isPromptMode ? `${chartsSection}${summarySection}` : `${summarySection}${chartsSection}`)}
  `;

  document.querySelector('.chart-generate-button')?.addEventListener('click', generateCharts);
  document.querySelector('.chart-request-input')?.addEventListener('input', (event) => {
    chartRequestText = event.target.value;
  });
}

function renderGeneratedChart(chart) {
  if (chart.chartType === 'line') return renderLineChart(chart);
  if (chart.chartType === 'bar') return renderBarChart(chart);
  if (chart.chartType === 'donut') return renderDonutChart(chart);
  return renderScorecard(chart);
}

function renderLineChart(chart) {
  const metricContext = resolvePrimaryMetric(chart);
  const valueLabel = chart.valueLabel || metricContext?.label || 'Value';
  const xAxisLabel = chart.xAxisLabel || 'Observation date';
  const plot = { left: 88, right: 28, top: 20, bottom: 62, width: 644, height: 278 };
  const orderedPoints = sortLinePoints(chart.data.points);
  const max = Math.max(...orderedPoints.map((point) => point.value));
  const min = Math.min(...orderedPoints.map((point) => point.value));
  const range = Math.max(max - min, 1);
  const scaledPoints = orderedPoints.map((point, index) => {
    const x = plot.left + (index / Math.max(orderedPoints.length - 1, 1)) * plot.width;
    const y = plot.top + ((max - point.value) / range) * plot.height;
    return { ...point, x, y };
  });
  const linePoints = scaledPoints.map((point) => `${point.x},${point.y}`).join(' ');
  const yTicks = [max, min + (range / 2), min].map((value, index) => ({
    key: `y-${index}`,
    value,
    y: plot.top + (index / 2) * plot.height,
  }));
  const xLabelPoints = chooseXAxisLabels(scaledPoints);
  const labels = [scaledPoints[0], scaledPoints[scaledPoints.length - 1]]
    .filter(Boolean)
    .map((point) => `<span>${formatShortDate(point.label)}: ${formatValue(point.value)}</span>`)
    .join('');
  const rangeLabel = orderedPoints.length > 1
    ? `${formatShortDate(orderedPoints[0].label)} to ${formatShortDate(orderedPoints[orderedPoints.length - 1].label)}`
    : formatShortDate(orderedPoints[0]?.label || '');

  return `<article class="chart-card chart-card-wide">
    <div class="metric-chart-head">
      <div><span>${pretty(chart.chartType)} chart</span><h3>${chart.title}</h3></div>
      <strong>${scaledPoints.length}</strong>
    </div>
    <p>${chart.rationale}</p>
    <svg class="real-chart-svg line-chart-svg" viewBox="0 0 760 360" role="img" aria-label="${chart.title}">
      <text x="${plot.left + (plot.width / 2)}" y="346" text-anchor="middle" class="chart-axis-title">${escapeHtml(xAxisLabel)}</text>
      <text x="22" y="${plot.top + (plot.height / 2)}" text-anchor="middle" class="chart-axis-title" transform="rotate(-90 22 ${plot.top + (plot.height / 2)})">${escapeHtml(valueLabel)}</text>
      ${yTicks.map((tick) => `<g>
        <line x1="${plot.left}" y1="${tick.y}" x2="${plot.left + plot.width}" y2="${tick.y}" class="chart-gridline"></line>
        <line x1="${plot.left - 8}" y1="${tick.y}" x2="${plot.left}" y2="${tick.y}" class="chart-tick"></line>
        <text x="${plot.left - 14}" y="${tick.y + 5}" text-anchor="end" class="chart-axis-label">${formatChartValue(tick.value, chart)}</text>
      </g>`).join('')}
      <line x1="${plot.left}" y1="${plot.top + plot.height}" x2="${plot.left + plot.width}" y2="${plot.top + plot.height}" class="chart-axis chart-axis-strong"></line>
      <line x1="${plot.left}" y1="${plot.top}" x2="${plot.left}" y2="${plot.top + plot.height}" class="chart-axis chart-axis-strong"></line>
      ${xLabelPoints.map((point) => `<g>
        <line x1="${point.x}" y1="${plot.top + plot.height}" x2="${point.x}" y2="${plot.top + plot.height + 8}" class="chart-tick"></line>
        <text x="${point.x}" y="${plot.top + plot.height + 28}" text-anchor="middle" class="chart-axis-label">${escapeHtml(formatShortDate(point.label))}</text>
      </g>`).join('')}
      <polyline points="${linePoints}" fill="none" stroke="currentColor" stroke-width="5" stroke-linecap="round" stroke-linejoin="round"></polyline>
      ${scaledPoints.map((point, index) => `<circle cx="${point.x}" cy="${point.y}" r="${index === scaledPoints.length - 1 ? 6 : 4.5}"></circle>`).join('')}
    </svg>
    <div class="chart-stats">
      ${metricContext?.label ? `<span>${escapeHtml(metricContext.label)}</span>` : ''}
      ${metricContext?.source ? `<span>${escapeHtml(metricContext.source)}</span>` : ''}
      ${rangeLabel ? `<span>${escapeHtml(rangeLabel)}</span>` : ''}
      <span>${formatCountLabel(orderedPoints.length, chart.countLabelSingular || 'observation')}</span>
      ${labels}
    </div>
  </article>`;
}

function renderBarChart(chart) {
  const metricContext = resolvePrimaryMetric(chart);
  const valueLabel = chart.valueLabel || metricContext?.label || 'Value';
  const xAxisLabel = chart.xAxisLabel || 'Observation period';
  const hasDenseTimeSeries = chart.data.bars.length > 8;
  const plot = hasDenseTimeSeries
    ? { left: 76, right: 20, top: 20, bottom: 72, width: 712, height: 250 }
    : { left: 72, right: 20, top: 20, bottom: 62, width: 648, height: 238 };
  const maxValue = Math.max(...chart.data.bars.map((bar) => bar.value), 0);
  const midpoint = maxValue / 2;
  const yTicks = [maxValue, midpoint, 0].map((value, index) => ({
    value,
    y: plot.top + (index / 2) * plot.height,
  }));
  const barWidth = Math.max((plot.width / Math.max(chart.data.bars.length, 1)) - 8, 14);
  const bars = chart.data.bars.map((bar, index) => {
    const x = plot.left + (index * (plot.width / Math.max(chart.data.bars.length, 1))) + 4;
    const height = maxValue ? (bar.value / maxValue) * plot.height : 0;
    const y = plot.top + plot.height - height;
    return { ...bar, x, y, width: barWidth, height };
  });
  const xLabels = chooseBarXAxisLabels(bars);
  const rangeLabel = buildCategoryRangeLabel(chart.data.bars.map((bar) => formatCategoryLabel(bar.label)));
  const chartClass = hasDenseTimeSeries ? 'chart-card chart-card-wide' : 'chart-card';

  return `<article class="${chartClass}">
    <div class="metric-chart-head">
      <div><span>${pretty(chart.chartType)} chart</span><h3>${chart.title}</h3></div>
      <strong>${chart.data.bars.length}</strong>
    </div>
    <p>${chart.rationale}</p>
    <svg class="real-chart-svg bar-chart-svg" viewBox="0 0 820 340" role="img" aria-label="${chart.title}">
      <text x="${plot.left + (plot.width / 2)}" y="324" text-anchor="middle" class="chart-axis-title">${escapeHtml(xAxisLabel)}</text>
      <text x="20" y="${plot.top + (plot.height / 2)}" text-anchor="middle" class="chart-axis-title" transform="rotate(-90 20 ${plot.top + (plot.height / 2)})">${escapeHtml(valueLabel)}</text>
      ${yTicks.map((tick) => `<g>
        <line x1="${plot.left}" y1="${tick.y}" x2="${plot.left + plot.width}" y2="${tick.y}" class="chart-gridline"></line>
        <line x1="${plot.left - 8}" y1="${tick.y}" x2="${plot.left}" y2="${tick.y}" class="chart-tick"></line>
        <text x="${plot.left - 14}" y="${tick.y + 5}" text-anchor="end" class="chart-axis-label">${formatBarValue(tick.value, chart)}</text>
      </g>`).join('')}
      <line x1="${plot.left}" y1="${plot.top + plot.height}" x2="${plot.left + plot.width}" y2="${plot.top + plot.height}" class="chart-axis chart-axis-strong"></line>
      <line x1="${plot.left}" y1="${plot.top}" x2="${plot.left}" y2="${plot.top + plot.height}" class="chart-axis chart-axis-strong"></line>
      ${bars.map((bar) => `<rect x="${bar.x}" y="${bar.y}" width="${bar.width}" height="${Math.max(bar.height, 2)}" rx="4" class="chart-bar"></rect>`).join('')}
      ${xLabels.map((bar) => `<g>
        <line x1="${bar.x + (bar.width / 2)}" y1="${plot.top + plot.height}" x2="${bar.x + (bar.width / 2)}" y2="${plot.top + plot.height + 8}" class="chart-tick"></line>
        <text x="${bar.x + (bar.width / 2)}" y="${plot.top + plot.height + 30}" text-anchor="middle" class="chart-axis-label">${escapeHtml(formatCategoryLabel(bar.label))}</text>
      </g>`).join('')}
    </svg>
    <div class="chart-stats">
      <span>${escapeHtml(valueLabel)}</span>
      ${metricContext?.label ? `<span>${escapeHtml(metricContext.label)}</span>` : ''}
      ${metricContext?.source ? `<span>${escapeHtml(metricContext.source)}</span>` : ''}
      ${rangeLabel ? `<span>${escapeHtml(rangeLabel)}</span>` : ''}
      <span>${formatCountLabel(bars.length, chart.countLabelSingular || 'bar')}</span>
      <span>Peak: ${formatBarValue(maxValue, chart)}</span>
    </div>
  </article>`;
}

function renderDonutChart(chart) {
  const metricContext = resolvePrimaryMetric(chart);
  const valueLabel = chart.valueLabel || 'Count';
  const total = chart.data.slices.reduce((sum, slice) => sum + slice.value, 0);
  const colors = ['#2d546e', '#6f8aa0', '#c0874d', '#c95f4a', '#9ea8b0'];
  let startAngle = 0;
  const slices = chart.data.slices.map((slice, index) => {
    const portion = total ? slice.value / total : 0;
    const endAngle = startAngle + (portion * Math.PI * 2);
    const path = donutSlicePath(50, 50, 38, 24, startAngle, endAngle);
    startAngle = endAngle;
    return {
      ...slice,
      color: colors[index % colors.length],
      path,
      share: total ? Math.round(portion * 100) : 0,
    };
  });

  return `<article class="chart-card">
    <div class="metric-chart-head">
      <div><span>${pretty(chart.chartType)} chart</span><h3>${chart.title}</h3></div>
      <strong>${total}</strong>
    </div>
    <p>${chart.rationale}</p>
    <div class="donut-layout">
      <svg class="donut-chart-svg" viewBox="0 0 100 100" role="img" aria-label="${chart.title}">
        ${slices.map((slice) => `<path d="${slice.path}" fill="${slice.color}"></path>`).join('')}
        <circle cx="50" cy="50" r="18" fill="#ffffff"></circle>
        <text x="50" y="47" text-anchor="middle" class="donut-number">${total}</text>
        <text x="50" y="57" text-anchor="middle" class="donut-label">total</text>
      </svg>
      <div class="donut-legend">
        ${slices.map((slice) => `<div class="legend-row"><span class="legend-swatch" style="background:${slice.color}"></span><strong>${escapeHtml(slice.label)}</strong><em>${formatValue(slice.value)} (${slice.share}%)</em></div>`).join('')}
      </div>
    </div>
    <div class="chart-stats">
      <span>${escapeHtml(valueLabel)}</span>
      <span>Share of total</span>
      ${metricContext?.label ? `<span>${escapeHtml(metricContext.label)}</span>` : ''}
      ${chart.sourceTitles?.length ? `<span>${escapeHtml(chart.sourceTitles[0])}</span>` : ''}
      <span>${formatCountLabel(slices.length, chart.countLabelSingular || 'category')}</span>
      <span>Total: ${formatValue(total)}</span>
    </div>
  </article>`;
}

function renderScorecard(chart) {
  const metricContext = resolvePrimaryMetric(chart);
  return `<article class="chart-card">
    <div class="metric-chart-head">
      <div><span>${pretty(chart.chartType)} chart</span><h3>${chart.title}</h3></div>
      <strong>${chart.data.items.length}</strong>
    </div>
    <p>${chart.rationale}</p>
    <div class="event-list">
      ${chart.data.items.map((item) => `<div><span>${escapeHtml(item.label)}</span><strong>${escapeHtml(item.value)}</strong>${item.context ? `<small class="scorecard-context">${escapeHtml(item.context)}</small>` : ''}</div>`).join('')}
    </div>
    <div class="chart-stats">
      ${metricContext?.label ? `<span>${escapeHtml(metricContext.label)}</span>` : ''}
      ${metricContext?.source ? `<span>${escapeHtml(metricContext.source)}</span>` : ''}
      <span>${formatCountLabel(chart.data.items.length, chart.countLabelSingular || 'item')}</span>
    </div>
  </article>`;
}

async function generateCharts() {
  const requestText = chartRequestText.trim();
  const isPromptRequest = Boolean(requestText);
  isGenerating = true;
  generationError = '';
  if (isPromptRequest) hasGeneratedPromptCharts = false;
  render();
  try {
    syncPromptUrl(requestText);
    const response = await fetch('/api/generate-charts', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ chartRequest: requestText }),
    });
    const payload = await response.json();
    if (!response.ok) throw new Error(payload.error || `Request failed with ${response.status}`);
    generatedCharts = Array.isArray(payload.charts) && payload.charts.length ? payload.charts : defaultCharts;
    hasGeneratedPromptCharts = isPromptRequest;
  } catch (error) {
    generationError = error.message;
    generatedCharts = defaultCharts;
  } finally {
    isGenerating = false;
    render();
  }
}

function readPromptFromUrl() {
  const url = new URL(window.location.href);
  return url.searchParams.get('prompt')?.trim() || '';
}

function readViewModeFromUrl() {
  const url = new URL(window.location.href);
  return url.searchParams.get('view')?.trim() || '';
}

function syncPromptUrl(promptText) {
  const url = new URL(window.location.href);
  if (promptText) {
    url.searchParams.set('prompt', promptText);
    if (!url.searchParams.get('view')) url.searchParams.set('view', 'clean');
  } else {
    url.searchParams.delete('prompt');
    url.searchParams.delete('view');
  }
  window.history.replaceState({}, '', `${url.pathname}${url.search}${url.hash}`);
}

function pretty(value) {
  return value.replaceAll('_', ' ');
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"]/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[character]));
}

function formatShortDate(value) {
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? value : date.toLocaleDateString(undefined, { month: 'short', year: 'numeric' });
}

function formatValue(value) {
  return Number.isFinite(value) ? value.toLocaleString() : String(value);
}

function formatAxisNumber(value) {
  return new Intl.NumberFormat(undefined, {
    notation: Math.abs(value) >= 10000 ? 'compact' : 'standard',
    maximumFractionDigits: Math.abs(value) >= 100 ? 0 : 1,
  }).format(value);
}

function formatChartValue(value, chart) {
  if (chart.valueFormat === 'percent') return `${formatAxisNumber(value)}%`;
  return formatAxisNumber(value);
}

function formatBarValue(value, chart) {
  return formatChartValue(value, chart);
}

function formatCountLabel(count, singular) {
  return `${count} ${count === 1 ? singular : pluralizeLabel(singular)}`;
}

function pluralizeLabel(label) {
  if (/(s|x|z|ch|sh)$/i.test(label)) return `${label}es`;
  if (label.endsWith('y') && !/[aeiou]y$/i.test(label)) return `${label.slice(0, -1)}ies`;
  return `${label}s`;
}

function resolvePrimaryMetric(chart) {
  const metricId = chart.metricIds?.[0];
  if (!metricId || !trackerData?.metrics) return null;
  return trackerData.metrics.find((metric) => metric.id === metricId) || null;
}

function buildCategoryRangeLabel(labels) {
  if (!labels.length) return '';
  if (labels.length === 1) return labels[0];
  return `${labels[0]} to ${labels[labels.length - 1]}`;
}

function formatCategoryLabel(label) {
  const monthlyMatch = String(label).match(/^(\d{4})-(\d{2})$/);
  if (monthlyMatch) {
    const date = new Date(`${monthlyMatch[1]}-${monthlyMatch[2]}-01T00:00:00`);
    return Number.isNaN(date.getTime())
      ? label
      : date.toLocaleDateString(undefined, { month: 'short', year: 'numeric' });
  }
  return label;
}

function chooseBarXAxisLabels(bars) {
  if (bars.length <= 6) return bars;
  const step = Math.ceil(bars.length / 5);
  return bars.filter((bar, index) => index % step === 0 || index === bars.length - 1);
}

function sortLinePoints(points) {
  return [...points].sort((left, right) => {
    const leftDate = Date.parse(left.label);
    const rightDate = Date.parse(right.label);
    if (Number.isNaN(leftDate) || Number.isNaN(rightDate)) return 0;
    return leftDate - rightDate;
  });
}

function chooseXAxisLabels(points) {
  if (points.length <= 2) return points;
  const middleIndex = Math.floor((points.length - 1) / 2);
  return [points[0], points[middleIndex], points[points.length - 1]]
    .filter((point, index, items) => items.findIndex((candidate) => candidate.x === point.x) === index);
}

function polarToCartesian(centerX, centerY, radius, angle) {
  return {
    x: centerX + (radius * Math.cos(angle - (Math.PI / 2))),
    y: centerY + (radius * Math.sin(angle - (Math.PI / 2))),
  };
}

function donutSlicePath(cx, cy, outerRadius, innerRadius, startAngle, endAngle) {
  const outerStart = polarToCartesian(cx, cy, outerRadius, startAngle);
  const outerEnd = polarToCartesian(cx, cy, outerRadius, endAngle);
  const innerEnd = polarToCartesian(cx, cy, innerRadius, endAngle);
  const innerStart = polarToCartesian(cx, cy, innerRadius, startAngle);
  const largeArcFlag = endAngle - startAngle > Math.PI ? 1 : 0;

  return [
    `M ${outerStart.x} ${outerStart.y}`,
    `A ${outerRadius} ${outerRadius} 0 ${largeArcFlag} 1 ${outerEnd.x} ${outerEnd.y}`,
    `L ${innerEnd.x} ${innerEnd.y}`,
    `A ${innerRadius} ${innerRadius} 0 ${largeArcFlag} 0 ${innerStart.x} ${innerStart.y}`,
    'Z',
  ].join(' ');
}

